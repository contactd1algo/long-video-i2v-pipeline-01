def detect_comfy_dir():
    for candidate in ["/workspace/runpod-slim/ComfyUI", "/workspace/ComfyUI", "/ComfyUI", "/opt/ComfyUI"]:
        if os.path.isdir(candidate):
            return candidate
    return "/workspace/runpod-slim/ComfyUI"

